import test from 'node:test';
import assert from 'node:assert/strict';
import { createRepeaterItem, registerItemRepeater } from '../radmanct-components/src/js/admin/atomic-repeater-control.js';

test('rich text repeater delegates image changes to native props and keeps sibling text', () => {
  const fields = { title: { default: '', label: 'Text', group:'content' }, image: { default: '', image: true, label: 'Inline image', group:'content' }, paint:{default:'solid',options:{solid:'Solid',gradient:'Gradient',image:'Image fill'},group:'text'}, gradient_end:{default:'#5667df',color:true,group:'text',condition:{paint:'gradient'}}, mask_image:{default:'',image:true,label:'Text fill image',group:'text',condition:{paint:'image'}} };
  fields.shadow_mode = {default:'inherit', options:{inherit:'Inherit',none:'None',custom:'Custom'},group:'text'};
  fields.shadow_horizontal = {default:0,min:-100,max:100,group:'text',condition:{shadow_mode:'custom'}};
  fields.image_width = {default:'',size:true,group:'image',min:0,max:2000};
  fields.image_radius_start_start = {default:'',size:true,group:'image',min:0,max:200,units:['px','%','em','rem']};
  fields.gradient_type = {default:'linear',group:'text',options:{linear:'Linear',radial:'Radial'},condition:{paint:'gradient'}};
  fields.gradient_angle = {default:90,group:'text',min:0,max:360,step:.1,condition:{paint:'gradient',gradient_type:'linear'}};
  fields.gradient_start_position = {default:0,group:'text',min:0,max:100,step:.1,condition:{paint:'gradient'}};
  fields.gradient_position = {default:'center center',group:'text',options:{'center center':'Center','top left':'Top left'},condition:{paint:'gradient',gradient_type:'radial'}};
  const row = createRepeaterItem(fields, { title: 'Work' }, 'rdct-text-segment');
  assert.equal(row.value.title.value, 'Work');
  assert.equal(row.value.image, undefined);
  assert.equal(row.value.image_width, undefined);
  assert.equal(row.value.image_radius_start_start, undefined);
  let control; let context; let committed; let activeGroup;
  const bound = { value: [row], disabled: false, propType: { item_prop_type: {} }, setValue: (next) => { committed = next; } };
  const element = {
    createElement: (type, props, ...children) => ({ type, props: { ...props, children } }),
    createContext: () => ({ Provider: 'Provider' }), useContext: () => context, useState: (initial) => [activeGroup ?? initial, (next) => {activeGroup = next;}],
  };
  const controls = Object.fromEntries(['Repeater', 'PropProvider', 'PropKeyProvider', 'TextControl', 'TextAreaControl', 'ColorControl', 'ImageControl', 'ControlFormLabel', 'NumberControl', 'SelectControl', 'SizeControl'].map((name) => [name, name]));
  controls.useBoundProp = () => bound;
  const imageProps={sizes:[{label:'Large',value:'large'},{label:'Client banner',value:'client-banner'}]};
  registerItemRepeater({ get: () => null, register: (_, component) => { control = component; } }, controls, { controlKey: 'rdct-text-segments', itemType: 'rdct-text-segment', imageProps, fields, initialGroup:'content', groupOptions:{content:'Content',text:'Text',image:'Image'}, labels: { item: 'Text segment' } }, element, { Stack: 'Stack', ToggleButtonGroup:'ToggleButtonGroup', ToggleButton:'ToggleButton' }, { stringPropTypeUtil: {} });
  const provider = control(); context = provider.props.value;
  const repeater = provider.props.children[0];
  const nodes = (node) => Array.isArray(node) ? node.flatMap(nodes) : node?.props ? [node, ...nodes(node.props.children)] : [];
  const content = repeater.props.itemSettings.Content({ value: row, index: 0 });
  const imageField = nodes(content).find((node) => node.props.fieldKey === 'image');
  const image = imageField.type(imageField.props);
  assert.equal(image.type, 'PropKeyProvider'); assert.equal(image.props.bind, 'image');
  assert.equal(image.props.children[0].type, 'ImageControl');
  assert.equal(image.props.children[0].props.sizes,imageProps.sizes);
  const tabs = nodes(content).find((node) => node.type === 'ToggleButtonGroup');
  assert.equal(nodes(tabs).filter((node) => node.type === 'ToggleButton').length,3);
  tabs.props.onChange(null,'text');
  const textFields = nodes(repeater.props.itemSettings.Content({value:row,index:0}));
  assert.equal(textFields.some((node) => node.props.fieldKey === 'image'),false);
  const shadowField = textFields.find((node) => node.props.fieldKey === 'shadow_horizontal');
  assert.equal(shadowField.type(shadowField.props),null);
  row.value.shadow_mode.value = 'custom';
  const shadowNumber = nodes(shadowField.type(shadowField.props)).find((node) => node.type === 'NumberControl');
  assert.equal(shadowNumber.props.min,-100); assert.equal(shadowNumber.props.max,100);
  row.value.shadow_horizontal.value = -8;
  row.value.shadow_mode.value = 'none';
  assert.equal(shadowField.type(shadowField.props),null);
  assert.equal(row.value.shadow_horizontal.value,-8);
  const gradientField = textFields.find((node) => node.props.fieldKey === 'gradient_end');
  assert.equal(gradientField.type(gradientField.props),null);
  row.value.paint.value = 'gradient';
  assert.ok(gradientField.type(gradientField.props));
  const angle = textFields.find((node) => node.props.fieldKey === 'gradient_angle');
  const position = textFields.find((node) => node.props.fieldKey === 'gradient_position');
  assert.ok(angle.type(angle.props)); assert.equal(position.type(position.props),null);
  row.value.gradient_type.value = 'radial';
  assert.equal(angle.type(angle.props),null);
  assert.ok(nodes(position.type(position.props)).some((node) => node.type === 'SelectControl'));
  const stop = textFields.find((node) => node.props.fieldKey === 'gradient_start_position');
  const nativeStop = nodes(stop.type(stop.props)).find((node) => node.type === 'NumberControl');
  assert.equal(nativeStop.props.shouldForceInt,false);
  assert.equal(nativeStop.props.step,.1);
  const maskField = textFields.find((node) => node.props.fieldKey === 'mask_image');
  assert.equal(maskField.type(maskField.props),null);
  row.value.paint.value = 'image';
  const maskControl = maskField.type(maskField.props);
  assert.equal(maskControl.type,'PropKeyProvider');
  assert.equal(maskControl.props.bind,'mask_image');
  assert.equal(maskControl.props.children[0].type,'ImageControl');
  assert.equal(committed,undefined);
  tabs.props.onChange(null,'image');
  const cornerField = nodes(repeater.props.itemSettings.Content({value:row,index:0})).find((node) => node.props.fieldKey === 'image_radius_start_start');
  const nativeCorner = nodes(cornerField.type(cornerField.props)).find((node) => node.type === 'SizeControl');
  assert.equal(nativeCorner.props.enablePropTypeUnits,true);
  assert.equal(nativeCorner.props.disableCustom,true);
  const sizeField = nodes(repeater.props.itemSettings.Content({value:row,index:0})).find((node) => node.props.fieldKey === 'image_width');
  const nativeSize = nodes(sizeField.type(sizeField.props)).find((node) => node.type === 'SizeControl');
  assert.equal(nativeSize.props.enablePropTypeUnits,true); assert.equal(nativeSize.props.disableCustom,true);
  tabs.props.onChange(null,'content');
  const nativeImage = { $$type: 'image', value: { src: { $$type: 'image-src', value: { id: { $$type: 'image-attachment-id', value: 7 } } } } };
  const itemProvider = nodes(content).find((node) => node.type === 'PropProvider' && node.props.propType === bound.propType.item_prop_type);
  itemProvider.props.setValue({ ...row.value, image: nativeImage });
  assert.equal(committed[0].value.image, nativeImage); assert.equal(committed[0].value.title.value, 'Work');
  bound.disabled = true;
  committed = undefined; control().props.children[0].props.setValues([]);
  assert.equal(committed, undefined);
});
